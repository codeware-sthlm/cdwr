import {
  type CompletionRecord,
  STUCK_MS,
  completionFile,
  completionHealth,
  parseRecord,
  recordFile,
  refreshMarker,
  stamp
} from './completion.logic';

const dirs = { cdwrHome: '/h/.cdwr', home: '/h' };

describe('completionFile', () => {
  it('puts fish in its completions directory', () => {
    expect(completionFile('fish', dirs)).toBe(
      '/h/.config/fish/completions/cdwr.fish'
    );
  });

  it.each(['zsh', 'bash'] as const)('puts %s under cdwr home', (shell) => {
    expect(completionFile(shell, dirs)).toBe(`/h/.cdwr/completion.${shell}`);
  });

  it('follows a custom cdwr home', () => {
    expect(completionFile('zsh', { cdwrHome: '/custom', home: '/h' })).toBe(
      '/custom/completion.zsh'
    );
  });
});

const record: CompletionRecord = {
  shell: 'zsh',
  file: '/h/.cdwr/completion.zsh',
  root: '/code/cdwr',
  tree: 'abc123'
};

describe('recordFile', () => {
  it('sits in cdwr home', () => {
    expect(recordFile('/h/.cdwr')).toBe('/h/.cdwr/completion.json');
  });

  it('has the refresh marker beside it, where the shim writes it', () => {
    expect(refreshMarker('/h/.cdwr')).toBe('/h/.cdwr/completion.refresh');
  });
});

describe('parseRecord', () => {
  it('reads what setup writes', () => {
    expect(parseRecord(JSON.stringify(record))).toEqual(record);
  });

  it('takes a null tree', () => {
    expect(parseRecord(JSON.stringify({ ...record, tree: null }))).toEqual({
      ...record,
      tree: null
    });
  });

  it.each([
    ['not JSON', 'nope'],
    ['an unknown shell', JSON.stringify({ ...record, shell: 'csh' })],
    ['no root', JSON.stringify({ ...record, root: undefined })]
  ])('ignores %s', (_, text) => {
    expect(parseRecord(text)).toBeUndefined();
  });
});

describe('stamp', () => {
  it('names the checkout and tree in the generated-by line', () => {
    const script = '#compdef cdwr\n# Generated by `cdwr completion zsh`\nx\n';
    expect(
      stamp(script, { root: '/code/cdwr', tree: '0123456789abcdef' })
    ).toBe(
      '#compdef cdwr\n# Generated by `cdwr completion zsh` from /code/cdwr at tree 0123456789ab\nx\n'
    );
  });

  it('keeps a $ in the path as it is', () => {
    expect(
      stamp('# Generated by x\n', { root: '/code/a$&b$1', tree: null })
    ).toBe('# Generated by x from /code/a$&b$1\n');
  });

  it('leaves the tree out outside git', () => {
    expect(
      stamp('# Generated by `cdwr completion bash`\n', {
        root: '/code/cdwr',
        tree: null
      })
    ).toBe('# Generated by `cdwr completion bash` from /code/cdwr\n');
  });
});

describe('completionHealth', () => {
  it('is missing without a file', () => {
    expect(
      completionHealth({ record, fileExists: false, tree: 'abc123' })
    ).toBe('missing');
  });

  it('is untracked when a script has no record', () => {
    expect(
      completionHealth({ record: undefined, fileExists: true, tree: 'abc123' })
    ).toBe('untracked');
  });

  it('is current while the checkout has the recorded tree', () => {
    expect(completionHealth({ record, fileExists: true, tree: 'abc123' })).toBe(
      'current'
    );
  });

  it('is refreshing once the checkout moved on', () => {
    expect(completionHealth({ record, fileExists: true, tree: 'def456' })).toBe(
      'refreshing'
    );
  });

  it('is refreshing while a started refresh is young', () => {
    expect(
      completionHealth({
        record,
        fileExists: true,
        tree: 'def456',
        markerAgeMs: STUCK_MS - 1
      })
    ).toBe('refreshing');
  });

  it('is stuck when a started refresh never finished', () => {
    expect(
      completionHealth({
        record,
        fileExists: true,
        tree: 'def456',
        markerAgeMs: STUCK_MS
      })
    ).toBe('stuck');
  });

  it('is unknown when git cannot say', () => {
    expect(
      completionHealth({ record, fileExists: true, tree: undefined })
    ).toBe('unknown');
  });
});
