import { join } from 'node:path';

import { SHELLS, type Shell } from '../cli/completion';

/** Where `cdwr setup` writes the completion script for a shell */
export const completionFile = (
  shell: Shell,
  dirs: { cdwrHome: string; home: string }
): string =>
  shell === 'fish'
    ? join(dirs.home, '.config', 'fish', 'completions', 'cdwr.fish')
    : join(dirs.cdwrHome, `completion.${shell}`);

/** What the last write of the completion script was rendered from */
export interface CompletionRecord {
  shell: Shell;
  file: string;
  /** The checkout `cdwr setup` linked from; only its code refreshes the script */
  root: string;
  /** `git rev-parse HEAD:tools/cdwr/src` in that checkout; null outside git */
  tree: string | null;
}

/** Beside prefs.json; the shim reads it after every run */
export const recordFile = (cdwrHome: string): string =>
  join(cdwrHome, 'completion.json');

/** Written by the shim when it starts a refresh, removed by the refresh once it wrote */
export const refreshMarker = (cdwrHome: string): string =>
  join(cdwrHome, 'completion.refresh');

/** A render takes seconds; a marker older than this belongs to a refresh that failed */
export const STUCK_MS = 2 * 60 * 1000;

export const parseRecord = (text: string): CompletionRecord | undefined => {
  try {
    const data = JSON.parse(text) as Partial<CompletionRecord>;
    return SHELLS.includes(data.shell as Shell) &&
      typeof data.file === 'string' &&
      typeof data.root === 'string' &&
      (typeof data.tree === 'string' || data.tree === null)
      ? {
          shell: data.shell as Shell,
          file: data.file,
          root: data.root,
          tree: data.tree
        }
      : undefined;
  } catch {
    return undefined;
  }
};

/** Names the checkout and tree in the script's generated-by line, for whoever reads it */
export const stamp = (
  script: string,
  from: Pick<CompletionRecord, 'root' | 'tree'>
): string =>
  // A function, so a `$` in the path is never read as a replacement pattern
  script.replace(
    /^# Generated by .*$/m,
    (line) =>
      `${line} from ${from.root}${from.tree ? ` at tree ${from.tree.slice(0, 12)}` : ''}`
  );

export type CompletionHealth =
  'current' | 'refreshing' | 'stuck' | 'untracked' | 'missing' | 'unknown';

/**
 * The installed script against the checkout it follows: the recorded tree
 * against that checkout's tree now. A script without a record predates the
 * refresh and never updates itself.
 */
export const completionHealth = (state: {
  record: CompletionRecord | undefined;
  fileExists: boolean;
  /** The recorded checkout's tree now; undefined when git can't say */
  tree: string | undefined;
  /** How long ago the shim started a refresh that hasn't finished */
  markerAgeMs?: number;
}): CompletionHealth =>
  !state.fileExists
    ? 'missing'
    : !state.record
      ? 'untracked'
      : state.tree === undefined
        ? 'unknown'
        : state.tree === state.record.tree
          ? 'current'
          : state.markerAgeMs !== undefined && state.markerAgeMs >= STUCK_MS
            ? 'stuck'
            : 'refreshing';
